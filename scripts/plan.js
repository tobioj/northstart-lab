// Generate the domain-specific plan once the root domain (and optionally platform/target) is known.
//   npm run plan -- --root-domain example.com [--environment staging] [--platform vercel|netlify|cloudflare|node]
//                   [--target cname.example-platform.com] [--record-type CNAME|A]
// Writes: configuration/deploy.env (non-secret, NORTHSTAR_ENABLED=false) and
//         deployment/generated/<root>/{dns-plan.md, zone.txt, cloudflare-waf-rule.txt, cloudflare-config-rule.txt}
// Contacts nothing. Creates no DNS records.
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { loadConfig } from '../configuration/config.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LANES = JSON.parse(readFileSync(join(ROOT, 'configuration', 'lanes.internal.json'), 'utf8')).lanes;

export const HOST_LABELS = { parent: 'northstar-parent', widget: 'northstar-widget', verify: 'northstar-verify' };
const EDGE_LANE = Object.values(LANES).find((l) => l.edge === 'cloudflare');

/** Pure plan builder (used by the CLI and by tests). */
export async function makePlan({ root, environment = 'staging', platform = '', target = '', recordType = 'CNAME' }) {
  root = String(root || '').toLowerCase().replace(/\.$/, '');
  platform = String(platform || '').toLowerCase();
  const type = String(recordType || 'CNAME').toUpperCase();
  const dnsTarget = target || '<HOSTING_PLATFORM_TARGET>';
  const hosts = Object.fromEntries(Object.entries(HOST_LABELS).map(([role, label]) => [role, `${label}.${root}`]));

  const env = {
    NORTHSTAR_ENABLED: 'false',
    NORTHSTAR_ENVIRONMENT: environment,
    NORTHSTAR_ROOT_DOMAIN: root,
    NORTHSTAR_PARENT_ORIGIN: `https://${hosts.parent}`,
    NORTHSTAR_WIDGET_ORIGIN: `https://${hosts.widget}`,
    NORTHSTAR_VERIFY_ORIGIN: `https://${hosts.verify}`,
    NORTHSTAR_TOKEN_TTL: '900',
    NORTHSTAR_PRODUCTION_HOSTS: '',
    NORTHSTAR_EVIDENCE_DIRECTORY: 'evidence',
    NORTHSTAR_REAL_WIDGETS: 'false',
  };
  // Validate with a throwaway signing key (the real one lives only in the platform secret manager).
  const check = await loadConfig({ ...env, NORTHSTAR_ENABLED: 'true', NORTHSTAR_TOKEN_SIGNING_KEY: 'plan-validation-only-'.padEnd(40, 'x') }, LANES);
  if (!check.ok) return { ok: false, errors: check.errors };

  // Proxy status: only the parent host is proxied (it carries the Cloudflare lane route), unless
  // the platform IS Cloudflare Workers (custom domains there are always proxied).
  const proxied = (role) => platform === 'cloudflare' || role === 'parent';
  const rows = Object.entries(hosts).map(([role, host]) => ({ role, name: HOST_LABELS[role], host, proxied: proxied(role) }));
  const lanePath = `/scenario/${EDGE_LANE.route}`;
  const waf = `(http.host eq "${hosts.parent}" and (http.request.uri.path eq "${lanePath}" or starts_with(http.request.uri.path, "${lanePath}/")))`;

  const envText = ['# Generated by scripts/plan.js - NON-SECRET values only.',
    '# NORTHSTAR_ENABLED stays false until you approve go-live (see deployment/deployment-checklist.md).',
    '# Secrets are NOT in this file. Set them only in the hosting platform secret manager:',
    '#   NORTHSTAR_TOKEN_SIGNING_KEY (required), NORTHSTAR_MANAGEMENT_AUTHORITY (optional)',
    ...Object.entries(env).map(([k, v]) => `${k}=${v}`)].join('\n') + '\n';

  const dnsMd = `# DNS record plan - ${root}

Generated by \`npm run plan\`. **Do not create these until the hosting platform has given you its DNS target.**
Exactly **three** records. All three point at the same hosting project; the app routes by the incoming \`Host\`.
${platform === 'cloudflare' ? '\n> Platform is Cloudflare Workers: you do NOT create these records by hand. Adding each hostname as a Worker *Custom Domain* creates them (always proxied).\n' : ''}
| Role | Hostname | Type | Name | Target | TTL | Cloudflare proxy |
|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r.role} | ${r.host} | ${type} | ${r.name} | ${dnsTarget} | 300 | ${platform === 'cloudflare' ? 'Proxied (automatic)' : r.proxied ? '**DNS only at first**, switch to Proxied in the Cloudflare-lane step' : 'DNS only (grey cloud)'} |`).join('\n')}
${platform === 'cloudflare' ? '' : `
**Order matters:** create all three as **DNS only** first. Vercel/Netlify can only issue each hostname's HTTPS certificate while Cloudflare is not proxying it. Switch \`${hosts.parent}\` to **Proxied** only after the platform shows its certificate as issued and \`https://${hosts.parent}/healthz\` works.
`}
Rules
- TTL 300 seconds to start (raise to 3600 once stable).
- Exactly one record per hostname: never an A record and a CNAME for the same name.
- No wildcard records.
- Nothing is added or changed on the root domain (\`${root}\`) or any other existing subdomain.
- Cloudflare-specific configuration applies only to \`${hosts.parent}\`, and the WAF rule only to the path \`${lanePath}\` on it (cloudflare-waf-rule.txt).
- If the platform hands you an IP address instead of a hostname, use type **A** with that IP for all three names (re-run: \`npm run plan -- --root-domain ${root} --record-type A --target <IP>\`).
`;

  const zone = [`; Northstar Lab - BIND zone fragment for ${root} (import into your DNS provider).`,
    '; Import only these three lines. Does not touch the apex or other records.',
    ...rows.map((r) => `${r.name.padEnd(18)} 300 IN ${type.padEnd(5)} ${type === 'CNAME' && !dnsTarget.endsWith('.') && !dnsTarget.startsWith('<') ? `${dnsTarget}.` : dnsTarget}`)].join('\n') + '\n';

  const wafText = `Rule name:   Northstar Cloudflare lane (test infrastructure)
Where:       Cloudflare dashboard > ${root} > Security > WAF > Custom rules
Expression:  ${waf}
Action:      Managed Challenge
State:       Save as DRAFT / disabled until https://${hosts.parent}/healthz returns 200 through the proxy.

Why it cannot leak: "http.host eq" is an exact match on the parent hostname and the path test
matches only ${lanePath} and below. It can never match ${root}, www.${root}, the widget or verify
hosts, or any other scenario route on the parent host.

Rollback (any one is enough, fastest first):
  1. Toggle the rule OFF (or delete it).
  2. Set the ${HOST_LABELS.parent} DNS record to "DNS only" (grey cloud).
`;

  const configRule = `Rule name:   Northstar parent host settings
Where:       Cloudflare dashboard > ${root} > Rules > Configuration Rules
When:        Hostname equals ${hosts.parent}
Then:        SSL/TLS: Full (strict)
             Email Obfuscation: Off
             Rocket Loader: Off
             Automatic HTTPS Rewrites: On
Why:         The parent host is proxied for the Cloudflare lane. Cloudflare must not inject
             scripts (email-decode, rocket-loader, /cdn-cgi/challenge-platform) into the OTHER
             scenario pages. Also keep Security > Bots > Bot Fight Mode OFF (zone-wide).
`;

  return { ok: true, env, envText, hosts, rows, dnsMd, zone, wafExpression: waf, wafText, configRule };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { values: a } = parseArgs({
    options: {
      'root-domain': { type: 'string' }, environment: { type: 'string', default: 'staging' },
      platform: { type: 'string', default: '' }, target: { type: 'string', default: '' },
      'record-type': { type: 'string', default: 'CNAME' },
    },
  });
  if (!a['root-domain']) { console.error('Usage: npm run plan -- --root-domain <ROOT_DOMAIN> [--platform ...] [--target ...]'); process.exit(1); }
  const plan = await makePlan({ root: a['root-domain'], environment: a.environment, platform: a.platform, target: a.target, recordType: a['record-type'] });
  if (!plan.ok) { console.error('Generated configuration would be invalid:\n - ' + plan.errors.join('\n - ')); process.exit(1); }
  const root = plan.env.NORTHSTAR_ROOT_DOMAIN;
  writeFileSync(join(ROOT, 'configuration', 'deploy.env'), plan.envText);
  const outDir = join(ROOT, 'deployment', 'generated', root);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'dns-plan.md'), plan.dnsMd);
  writeFileSync(join(outDir, 'zone.txt'), plan.zone);
  writeFileSync(join(outDir, 'cloudflare-waf-rule.txt'), plan.wafText);
  writeFileSync(join(outDir, 'cloudflare-config-rule.txt'), plan.configRule);
  console.log(`Wrote configuration/deploy.env and deployment/generated/${root}/ (dns-plan.md, zone.txt, cloudflare-waf-rule.txt, cloudflare-config-rule.txt)`);
  console.log(`Hosts: ${plan.rows.map((r) => `${r.role}=${r.host}`).join(', ')}`);
}
