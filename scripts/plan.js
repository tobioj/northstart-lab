// Generate the domain-specific plan once the root domain (and optionally platform/target) is known.
//   npm run plan -- --root-domain example.com [--environment staging] [--platform vercel|netlify|cloudflare|node]
//                   [--target cname.example-platform.com] [--record-type CNAME|A]
//                   [--hcaptcha-site-key <public>] [--recaptcha-site-key <public>]
// Writes: configuration/deploy.env (non-secret, NORTHSTAR_ENABLED=false) and
//         deployment/generated/<root>/{dns-plan.md, zone.txt, cloudflare-waf-rule.txt}
// Contacts nothing. Creates no DNS records.
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { loadConfig } from '../configuration/config.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LANES = JSON.parse(readFileSync(join(ROOT, 'configuration', 'lanes.internal.json'), 'utf8')).lanes;

const { values: a } = parseArgs({
  options: {
    'root-domain': { type: 'string' }, environment: { type: 'string', default: 'staging' },
    platform: { type: 'string', default: '' }, target: { type: 'string', default: '' },
    'record-type': { type: 'string', default: 'CNAME' },
    'hcaptcha-site-key': { type: 'string', default: '' }, 'recaptcha-site-key': { type: 'string', default: '' },
  },
});
const root = (a['root-domain'] || '').toLowerCase().replace(/\.$/, '');
if (!root) { console.error('Usage: npm run plan -- --root-domain <ROOT_DOMAIN> [--platform ...] [--target ...]'); process.exit(1); }
const platform = a.platform.toLowerCase();
const target = a.target || '<HOSTING_PLATFORM_TARGET>';
const type = a['record-type'].toUpperCase();

const env = { NORTHSTAR_ENABLED: 'false', NORTHSTAR_ENVIRONMENT: a.environment, NORTHSTAR_ROOT_DOMAIN: root };
for (const lane of Object.values(LANES)) env[lane.hostVariable] = `${lane.label}.${root}`;
env.NORTHSTAR_HCAPTCHA_SITE_KEY = a['hcaptcha-site-key'];
env.NORTHSTAR_RECAPTCHA_SITE_KEY = a['recaptcha-site-key'];
env.NORTHSTAR_ALLOWED_ORIGINS = '';
env.NORTHSTAR_PRODUCTION_HOSTS = '';
env.NORTHSTAR_EVIDENCE_DIRECTORY = 'evidence';

const check = loadConfig({ ...env, NORTHSTAR_ENABLED: 'true' }, LANES);
if (!check.ok) { console.error('Generated configuration would be invalid:\n - ' + check.errors.join('\n - ')); process.exit(1); }

const envText = ['# Generated by scripts/plan.js - NON-SECRET values only.',
  '# NORTHSTAR_ENABLED stays false until you approve go-live (see deployment/deployment-checklist.md).',
  ...Object.entries(env).map(([k, v]) => `${k}=${v}`)].join('\n') + '\n';
writeFileSync(join(ROOT, 'configuration', 'deploy.env'), envText);

// Proxy status: only lane-01 is proxied through Cloudflare, unless the platform IS Cloudflare
// Workers/Pages (custom domains there are always proxied; the WAF rule is still lane-01 only).
const proxied = (laneId) => platform === 'cloudflare' || laneId === 'lane-01';
const outDir = join(ROOT, 'deployment', 'generated', root);
mkdirSync(outDir, { recursive: true });

const rows = Object.entries(LANES).map(([id, l]) => ({ id, name: l.label, host: `${l.label}.${root}`, proxied: proxied(id) }));
const waf = `(http.host eq "northstar-01.${root}" and not starts_with(http.request.uri.path, "/.well-known/acme-challenge/") and not http.request.uri.path in {"/healthz" "/readyz" "/fixture-manifest.json"})`;

const dnsMd = `# DNS record plan - ${root}

Generated by \`npm run plan\`. **Do not create these until the hosting platform has given you its DNS target.**
${platform === 'cloudflare' ? '\n> Platform is Cloudflare Workers: you do NOT create these records by hand. Adding each hostname as a Worker *Custom Domain* creates them (always proxied).\n' : ''}
| Hostname | Type | Name | Target | TTL | Cloudflare proxy |
|---|---|---|---|---|---|
${rows.map((r) => `| ${r.host} | ${type} | ${r.name} | ${target} | 300 | ${r.proxied ? 'Proxied (orange cloud)' : 'DNS only (grey cloud)'} |`).join('\n')}

Rules
- TTL 300 seconds to start (raise to 3600 once stable).
- Exactly one record per hostname: never an A record and a CNAME for the same name.
- No wildcard records.
- Nothing is added or changed on the root domain (\`${root}\`) or any other existing subdomain.
- Only \`northstar-01.${root}\` carries Cloudflare-specific configuration (the WAF rule in cloudflare-waf-rule.txt).
- If the platform hands you an IP address instead of a hostname, use type **A** with that IP for all 12 names (re-run: \`npm run plan -- --root-domain ${root} --record-type A --target <IP>\`).
`;
writeFileSync(join(outDir, 'dns-plan.md'), dnsMd);

const zone = [`; Northstar Lab - BIND zone fragment for ${root} (import into your DNS provider).`,
  `; Import only these lines. Does not touch the apex or other records.`,
  ...rows.map((r) => `${r.name.padEnd(18)} 300 IN ${type.padEnd(5)} ${type === 'CNAME' && !target.endsWith('.') && !target.startsWith('<') ? `${target}.` : target}`)].join('\n') + '\n';
writeFileSync(join(outDir, 'zone.txt'), zone);

writeFileSync(join(outDir, 'cloudflare-waf-rule.txt'), `Rule name:   Northstar lane 01 (test infrastructure)
Where:       Cloudflare dashboard > ${root} > Security > WAF > Custom rules
Expression:  ${waf}
Action:      Managed Challenge
State:       Save as DRAFT / disabled until https://northstar-01.${root}/healthz returns 200 through the proxy.

Why it cannot leak: "http.host eq" is an exact match on one hostname, so it can never match
${root}, www.${root}, or any other northstar-* host. ACME (certificate) and health paths are excluded.

Rollback (any one is enough, fastest first):
  1. Toggle the rule OFF (or delete it).
  2. Set the northstar-01 DNS record to "DNS only" (grey cloud).
  3. Delete the northstar-01 DNS record.
`);

console.log(`Wrote configuration/deploy.env and deployment/generated/${root}/ (dns-plan.md, zone.txt, cloudflare-waf-rule.txt)`);
console.log(`Hosts: ${rows.map((r) => r.host).join(', ')}`);
